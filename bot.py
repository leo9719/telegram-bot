from telegram import Update
from telegram.ext import Application, MessageHandler, filters, ContextTypes
import os
import random

TOKEN = os.getenv("TOKEN")

if not TOKEN:
    print("❌ TOKEN не найден!")
    exit(1)

print("✅ Мощный психологический толкователь снов запущен!")

def interpret_dream(dream_text: str) -> str:
    text = dream_text.lower()
    
    intro = "🔮 Я очень внимательно проанализировал твой сон с психологической точки зрения, опираясь на подходы Юнга, Фрейда и классические символические значения."

    main_parts = []

    # ================= РАЗВЕРНУТЫЕ ТОЛКОВАНИЯ =================
    if any(w in text for w in ["летал", "летать", "полет", "летаю", "взлетел", "парю", "небо"]):
        main_parts.append(
            "**Полёт во сне** — это один из самых светлых и важных символов. "
            "Он говорит о сильном внутреннем желании свободы, расширения горизонтов и выхода за рамки привычной жизни. "
            "Твоя душа сейчас активно стремится к росту. Возможно, в реальности ты чувствуешь, что «зажат» обстоятельствами, ожиданиями других людей или собственными страхами. "
            "Сон показывает: у тебя есть потенциал подняться значительно выше текущего уровня. Это приглашение поверить в себя и начать двигаться к тому, чего ты действительно хочешь."
        )

    if any(w in text for w in ["падал", "падать", "упал", "сорвался", "летел вниз"]):
        main_parts.append(
            "**Падение** — очень честный сон. Он отражает глубокий страх потери контроля над своей жизнью. "
            "Сейчас ты можешь находиться в ситуации, где многое зависит не от тебя, или боишься, что «всё рухнет». "
            "Подсознание через этот образ показывает твою внутреннюю тревогу и одновременно — необходимость найти опору внутри себя, а не только во внешнем мире. "
            "Это важный сигнал: пора перестать держаться за то, что уже не работает, и научиться доверять процессу."
        )

    if any(w in text for w in ["преслед", "гонял", "убегал", "погоня", "догонял", "страшный человек"]):
        main_parts.append(
            "**Преследование** — это встреча с той частью себя, от которой ты пытаешься убежать. "
            "Это может быть подавленная вина, стыд, старые травмы, страх ответственности или не принятая эмоция. "
            "То, что тебя «преследует» во сне, почти всегда является частью твоей собственной личности, которую ты пока не готов принять. "
            "Сон мягко предлагает: пора развернуться и посмотреть этому страху в глаза — только так можно его исцелить."
        )

    if any(w in text for w in ["вода", "море", "река", "океан", "тонуть", "плыл", "купаться"]):
        main_parts.append(
            "**Вода** — это прямое отражение твоего эмоционального мира. "
            "Спокойная чистая вода говорит о внутренней гармонии и исцелении. Бурная, грязная или ты тонул — значит, сейчас внутри тебя очень сильные эмоции, которые ты, возможно, стараешься не замечать днём. "
            "Сон приглашает тебя не подавлять чувства, а прожить их. Эмоции хотят быть увиденными и принятыми."
        )

    if any(w in text for w in ["зуб", "зубы", "выпал", "выпадение"]):
        main_parts.append(
            "**Зубы** — древний символ личной силы, уверенности и способности проявлять себя в мире. "
            "Выпадение зубов часто приходит в периоды, когда человек чувствует себя уязвимым, боится потерять привлекательность, статус или контроль над ситуацией. "
            "Это приглашение поработать с самооценкой и внутренней уверенностью."
        )

    # Если ничего конкретного не нашлось
    if not main_parts:
        main_parts.append(
            "Твой сон — это глубокое послание от подсознания. Сейчас в твоей жизни идёт важный внутренний процесс переосмысления и трансформации. "
            "Ты находишься на пороге нового этапа, и психика активно готовит тебя к нему, показывая скрытые желания, страхи и ресурсы."
        )

    main = random.choice(main_parts)

    conclusion = (
        "\n\n💭 **Что с этим делать в реальной жизни?**\n"
        "Попробуй задать себе несколько вопросов:\n"
        "• Какие эмоции были самыми сильными во сне?\n"
        "• Что в этом сне особенно сильно зацепило?\n"
        "• Есть ли в моей текущей жизни что-то, что напоминает этот сон?\n\n"
        "Ответы на эти вопросы часто приходят сами в течение дня. Сон — это не приговор, а подсказка от твоей собственной мудрой психики."
    )

    return f"{intro}\n\n{main}{conclusion}"


async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text.strip()

    if len(text) < 10:
        await update.message.reply_text("Расскажи свой сон как можно подробнее, пожалуйста 😊")
        return

    await update.message.reply_text("🔮 Я очень глубоко погружаюсь в твой сон...")

    interpretation = interpret_dream(text)
    await update.message.reply_text(interpretation)


app = Application.builder().token(TOKEN).build()
app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))

print("🚀 Бот работает...")
app.run_polling()